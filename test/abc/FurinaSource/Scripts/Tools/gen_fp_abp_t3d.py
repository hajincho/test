"""AnimGraph nodes for the rifle stance, pasted into ABP_Furina's AnimGraph (connections to the existing graph are made
by ue_fp_abp_connect.py afterwards):
  FP Idle/Walk/Run loops -> TwoWayBlends by FurinaWalk / FurinaIdle -> Slot DefaultSlot (fire/reload montages)
  -> LayeredBoneBlend (base = existing locomotion, blend = wrists+fingers only, curves = max) -> ModifyCurve AimPitch
AimPitch = NormalizeAxis(TryGetPawnOwner().GetBaseAimRotation().Pitch), evaluated as pure nodes inside the AnimGraph."""
import uuid, sys
OUT = sys.argv[1]
def g(): return uuid.uuid4().hex.upper()
STRUCT = "PinType.PinCategory=\"struct\",PinType.PinSubCategory=\"\",PinType.PinSubCategoryObject=\"/Script/CoreUObject.ScriptStruct'/Script/Engine.%s'\","
TAIL = 'PinType.PinSubCategoryMemberReference=(),PinType.PinValueType=(),PinType.ContainerType=None,PinType.bIsReference=False,PinType.bIsConst=False,PinType.bIsWeakPointer=False,PinType.bIsUObjectWrapper=False,PinType.bSerializeAsSinglePrecisionFloat=False,'
END = 'PersistentGuid=00000000000000000000000000000000,bHidden=False,bNotConnectable=False,bDefaultValueIsReadOnly=False,bDefaultValueIsIgnored=False,bAdvancedView=False,bOrphanedPin=False,)'
def pin(pid, name, cat, sub='', obj=None, out=False, links=(), default=None, struct=None):
    s = 'CustomProperties Pin (PinId=%s,PinName="%s",' % (pid, name)
    if out: s += 'Direction="EGPD_Output",'
    if struct: s += STRUCT % struct
    else: s += 'PinType.PinCategory="%s",PinType.PinSubCategory="%s",PinType.PinSubCategoryObject=%s,' % (cat, sub, ('"%s"' % obj) if obj else 'None')
    s += TAIL
    if default is not None: s += 'DefaultValue="%s",' % default
    if links: s += 'LinkedTo=(%s),' % ''.join('%s %s,' % l for l in links)
    return s + END
def pose(pid, name, out, links=()):
    s = pin(pid, name, None, struct='PoseLink', out=out, links=links)
    if not out: s = s.replace('PinType.bSerializeAsSinglePrecisionFloat=False,', 'PinType.bSerializeAsSinglePrecisionFloat=False,DefaultValue="(LinkID=-1,SourceLinkID=-1)",AutogeneratedDefaultValue="(LinkID=-1,SourceLinkID=-1)",', 1)
    return s
P = {k: g() for k in ['idle', 'walk', 'run', 'wa', 'wb', 'wo', 'ia', 'ib', 'io', 'si', 'so', 'lb_base', 'lb_0', 'lb_out',
                      'mc_src', 'mc_out', 'mc_val', 'own_self', 'own_ret', 'aim_self', 'aim_ret', 'br_in', 'br_r', 'br_p', 'br_y', 'na_in', 'na_ret']}
N = dict(idle='AnimGraphNode_SequencePlayer_FPIdle', walk='AnimGraphNode_SequencePlayer_FPWalk', run='AnimGraphNode_SequencePlayer_FPRun',
         tw='AnimGraphNode_TwoWayBlend_FPWalk', ti='AnimGraphNode_TwoWayBlend_FPIdle', slot='AnimGraphNode_Slot_FP',
         lb='AnimGraphNode_LayeredBoneBlend_FP', mc='AnimGraphNode_ModifyCurve_Aim',
         own='K2Node_CallFunction_FPOwner', aim='K2Node_CallFunction_FPAim', br='K2Node_CallFunction_FPBreak', na='K2Node_CallFunction_FPNorm')
def seq(name, asset, key, x, y, to):
    return ('/Script/AnimGraph.AnimGraphNode_SequencePlayer', N[name], ["Node=(Sequence=\"/Script/Engine.AnimSequence'/Game/Furina/FP/Anim/%s.%s'\",bLoopAnimation=True)" % (asset, asset)],
            x, y, [pose(P[key], 'Pose', True, [to])])
X, Y = -1600, 900
nodes = [
    seq('run', 'AS_Furina_FP_Run_Loop', 'run', X, Y, (N['tw'], P['wa'])),
    seq('walk', 'AS_Furina_FP_Walk_F_Loop', 'walk', X, Y + 200, (N['tw'], P['wb'])),
    seq('idle', 'AS_Furina_FP_Idle_Loop', 'idle', X, Y + 400, (N['ti'], P['ib'])),
    ('/Script/AnimGraph.AnimGraphNode_TwoWayBlend', N['tw'], ['BlendNode=(AlphaInputType=Curve,AlphaCurveName="FurinaWalk")'], X + 400, Y + 100,
     [pose(P['wa'], 'A', False, [(N['run'], P['run'])]), pose(P['wb'], 'B', False, [(N['walk'], P['walk'])]), pose(P['wo'], 'Pose', True, [(N['ti'], P['ia'])])]),
    ('/Script/AnimGraph.AnimGraphNode_TwoWayBlend', N['ti'], ['BlendNode=(AlphaInputType=Curve,AlphaCurveName="FurinaIdle")'], X + 750, Y + 250,
     [pose(P['ia'], 'A', False, [(N['tw'], P['wo'])]), pose(P['ib'], 'B', False, [(N['idle'], P['idle'])]), pose(P['io'], 'Pose', True, [(N['slot'], P['si'])])]),
    ('/Script/AnimGraph.AnimGraphNode_Slot', N['slot'], ['Node=(SlotName="DefaultSlot")'], X + 1100, Y + 250,
     [pose(P['si'], 'Source', False, [(N['ti'], P['io'])]), pose(P['so'], 'Pose', True, [(N['lb'], P['lb_0'])])]),
    ('/Script/AnimGraph.AnimGraphNode_LayeredBoneBlend', N['lb'],
     ['Node=(BlendPoses=((LinkID=-1,SourceLinkID=-1)),LayerSetup=((BranchFilters=((BoneName="Right-wrist",BlendDepth=0),(BoneName="Left-wrist",BlendDepth=0)))),BlendWeights=(1.000000),CurveBlendOption=UseMaxValue)'],
     X + 1450, Y,
     [pose(P['lb_base'], 'BasePose', False), pose(P['lb_0'], 'BlendPoses_0', False, [(N['slot'], P['so'])]), pose(P['lb_out'], 'Pose', True, [(N['mc'], P['mc_src'])])]),
    ('/Script/AnimGraph.AnimGraphNode_ModifyCurve', N['mc'], ['Node=(CurveValues=(0.000000),CurveNames=("AimPitch"),Alpha=1.000000,ApplyMode=Blend)'], X + 1800, Y,
     [pose(P['mc_src'], 'SourcePose', False, [(N['lb'], P['lb_out'])]), pose(P['mc_out'], 'Pose', True),
      pin(P['mc_val'], 'CurveValues_0', 'real', 'float', default='0.0', links=[(N['na'], P['na_ret'])])]),
    ('/Script/BlueprintGraph.K2Node_CallFunction', N['own'], ['bIsPureFunc=True', "FunctionReference=(MemberParent=\"/Script/CoreUObject.Class'/Script/Engine.AnimInstance'\",MemberName=\"TryGetPawnOwner\")"],
     X + 400, Y + 700,
     [pin(P['own_self'], 'self', 'object', obj="/Script/CoreUObject.Class'/Script/Engine.AnimInstance'"),
      pin(P['own_ret'], 'ReturnValue', 'object', obj="/Script/CoreUObject.Class'/Script/Engine.Pawn'", out=True, links=[(N['aim'], P['aim_self'])])]),
    ('/Script/BlueprintGraph.K2Node_CallFunction', N['aim'], ['bIsPureFunc=True', "FunctionReference=(MemberParent=\"/Script/CoreUObject.Class'/Script/Engine.Pawn'\",MemberName=\"GetBaseAimRotation\")"],
     X + 750, Y + 700,
     [pin(P['aim_self'], 'self', 'object', obj="/Script/CoreUObject.Class'/Script/Engine.Pawn'", links=[(N['own'], P['own_ret'])]),
      pin(P['aim_ret'], 'ReturnValue', None, struct='Rotator', out=True, links=[(N['br'], P['br_in'])]).replace("'/Script/Engine.Rotator'", "'/Script/CoreUObject.Rotator'")]),
    ('/Script/BlueprintGraph.K2Node_CallFunction', N['br'], ['bIsPureFunc=True', "FunctionReference=(MemberParent=\"/Script/CoreUObject.Class'/Script/Engine.KismetMathLibrary'\",MemberName=\"BreakRotator\")"],
     X + 1100, Y + 700,
     [pin(P['br_in'], 'InRot', None, struct='Rotator', links=[(N['aim'], P['aim_ret'])]).replace("'/Script/Engine.Rotator'", "'/Script/CoreUObject.Rotator'"),
      pin(P['br_r'], 'Roll', 'real', 'double', out=True), pin(P['br_p'], 'Pitch', 'real', 'double', out=True, links=[(N['na'], P['na_in'])]),
      pin(P['br_y'], 'Yaw', 'real', 'double', out=True)]),
    ('/Script/BlueprintGraph.K2Node_CallFunction', N['na'], ['bIsPureFunc=True', "FunctionReference=(MemberParent=\"/Script/CoreUObject.Class'/Script/Engine.KismetMathLibrary'\",MemberName=\"NormalizeAxis\")"],
     X + 1450, Y + 700,
     [pin(P['na_in'], 'Angle', 'real', 'double', default='0.0', links=[(N['br'], P['br_p'])]),
      pin(P['na_ret'], 'ReturnValue', 'real', 'double', out=True, links=[(N['mc'], P['mc_val'])])]),
]
out = []
for cls, name, props, x, y, pins in nodes:
    out.append('Begin Object Class=%s Name="%s"' % (cls, name))
    out += ['   ' + q for q in props]
    out += ['   NodePosX=%d' % x, '   NodePosY=%d' % y, '   NodeGuid=%s' % g()]
    out += ['   ' + q for q in pins]
    out.append('End Object')
open(OUT, 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out) + '\n')
print('ok', len(nodes))
