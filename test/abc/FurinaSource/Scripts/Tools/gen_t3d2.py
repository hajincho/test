"""ABP_Furina graph v2: retarget + old Unity idle (curve-blended) -> CR_FurinaSecondary."""
import uuid, sys
S = sys.argv[1]
def gid(): return uuid.uuid4().hex.upper()
POSE = "PinType.PinCategory=\"struct\",PinType.PinSubCategory=\"\",PinType.PinSubCategoryObject=\"/Script/CoreUObject.ScriptStruct'/Script/Engine.PoseLink'\",PinType.PinSubCategoryMemberReference=(),PinType.PinValueType=(),PinType.ContainerType=None,PinType.bIsReference=False,PinType.bIsConst=False,PinType.bIsWeakPointer=False,PinType.bIsUObjectWrapper=False,PinType.bSerializeAsSinglePrecisionFloat=False"
def pin(pid, name, out, link=None):
    s = 'CustomProperties Pin (PinId=%s,PinName="%s",' % (pid, name)
    if out: s += 'Direction="EGPD_Output",'
    s += POSE + ','
    if not out: s += 'DefaultValue="(LinkID=-1,SourceLinkID=-1)",AutogeneratedDefaultValue="(LinkID=-1,SourceLinkID=-1)",'
    if link: s += 'LinkedTo=(%s %s,),' % link
    s += 'PersistentGuid=00000000000000000000000000000000,bHidden=False,bNotConnectable=False,bDefaultValueIsReadOnly=False,bDefaultValueIsIgnored=False,bAdvancedView=False,bOrphanedPin=False,)'
    return s
RTG = "/Script/IKRig.IKRetargeter'/Game/Furina/Retarget/RTG_Manny_To_Furina.RTG_Manny_To_Furina'"
p = {k: gid() for k in ['ra', 'rb', 'seq', 'twa', 'twb', 'two', 'lbase', 'lb0', 'lout', 'crin', 'crout']}
nodes = [
 ('/Script/IKRigDeveloper.AnimGraphNode_RetargetPoseFromMesh', 'AnimGraphNode_RetargetPoseFromMesh_0',
  '(RetargetFrom=ParentSkeletalMeshComponent,IKRetargeterAsset="%s")' % RTG, -1200, -200,
  [pin(p['ra'], 'Pose', True, ('AnimGraphNode_TwoWayBlend_0', p['twa']))]),
 ('/Script/AnimGraph.AnimGraphNode_SequencePlayer', 'AnimGraphNode_SequencePlayer_0',
  "(Sequence=\"/Script/Engine.AnimSequence'/Game/Furina/Anim/AS_Furina_Idle.AS_Furina_Idle'\",bLoopAnimation=True)", -1200, 0,
  [pin(p['seq'], 'Pose', True, ('AnimGraphNode_TwoWayBlend_0', p['twb']))]),
 ('/Script/AnimGraph.AnimGraphNode_TwoWayBlend', 'AnimGraphNode_TwoWayBlend_0',
  '(AlphaInputType=Curve,AlphaCurveName="FurinaIdle")', -800, -100,
  [pin(p['twa'], 'A', False, ('AnimGraphNode_RetargetPoseFromMesh_0', p['ra'])),
   pin(p['twb'], 'B', False, ('AnimGraphNode_SequencePlayer_0', p['seq'])),
   pin(p['two'], 'Pose', True, ('AnimGraphNode_LayeredBoneBlend_0', p['lb0']))]),
 ('/Script/IKRigDeveloper.AnimGraphNode_RetargetPoseFromMesh', 'AnimGraphNode_RetargetPoseFromMesh_1',
  '(RetargetFrom=ParentSkeletalMeshComponent,IKRetargeterAsset="%s")' % RTG, -800, -400,
  [pin(p['rb'], 'Pose', True, ('AnimGraphNode_LayeredBoneBlend_0', p['lbase']))]),
 ('/Script/AnimGraph.AnimGraphNode_LayeredBoneBlend', 'AnimGraphNode_LayeredBoneBlend_0',
  '(BlendPoses=((LinkID=-1,SourceLinkID=-1)),LayerSetup=((BranchFilters=((BoneName="Hips",BlendDepth=0)))),BlendWeights=(1.000000),CurveBlendOption=UseMaxValue)', -400, -250,
  [pin(p['lbase'], 'BasePose', False, ('AnimGraphNode_RetargetPoseFromMesh_1', p['rb'])),
   pin(p['lb0'], 'BlendPoses_0', False, ('AnimGraphNode_TwoWayBlend_0', p['two'])),
   pin(p['lout'], 'Pose', True, ('AnimGraphNode_ControlRig_0', p['crin']))]),
 ('/Script/ControlRigDeveloper.AnimGraphNode_ControlRig', 'AnimGraphNode_ControlRig_0',
  "(ControlRigAssetReference=(BlueprintRigClass=\"/Script/ControlRigDeveloper.ControlRigBlueprintGeneratedClass'/Game/Furina/CR_FurinaSecondary.CR_FurinaSecondary_C'\"))", 0, -250,
  [pin(p['crin'], 'Source', False, ('AnimGraphNode_LayeredBoneBlend_0', p['lout'])),
   pin(p['crout'], 'Pose', True)]),
]
out = []
for cls, name, nodetext, x, y, pins in nodes:
    out.append('Begin Object Class=%s Name="%s"' % (cls, name))
    if nodetext: out.append('   %s=%s' % ('BlendNode' if 'TwoWayBlend' in cls else 'Node', nodetext))
    out += ['   NodePosX=%d' % x, '   NodePosY=%d' % y, '   NodeGuid=%s' % gid()]
    out += ['   ' + q for q in pins]
    out.append('End Object')
open(S + r'\abp_graph2.t3d', 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out) + '\n')
print('ok')

