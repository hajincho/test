"""Generate the ABP_Furina AnimGraph as T3D text: RetargetPoseFromMesh -> LocalToComponent -> 12 AnimDynamics cloth chains -> ComponentToLocal.
Cloth parameters come from the SilkClothDynamics settings saved on the Unity 'Furina Player'."""
import json, uuid, sys
S = sys.argv[1]
cloth = json.load(open(S + r'\cloth_bones.json', encoding='utf-8'))
pl = json.load(open(S + r'\furina_player.json', encoding='utf-8'))
local = {n['name']: n['lp'] for n in pl['nodes'].values() if n['path'].startswith('Furina Player/ModelRoot/Furina/')}

def ue_name(n): return n.replace(' ', '-')
def ue_vec(n):  # Unity local position (m) -> UE local (cm): FBX->Unity flips X, FBX->UE flips Y
    p = local[n]; return (-p['x'] * 100, -p['y'] * 100, p['z'] * 100)
def v(t): return '(X=%.4f,Y=%.4f,Z=%.4f)' % t
def scale(t, k): return tuple(c * k for c in t)
def gid(): return uuid.uuid4().hex.upper()

by = {c['bone']: c for c in cloth}
kids = {}
for c in cloth: kids.setdefault(c['parent'], []).append(c['bone'])
chains = []
for c in cloth:
    if c['depth'] == 0:
        ch = [c['bone']]
        while kids.get(ch[-1]): ch.append(kids[ch[-1]][0])
        chains.append(ch)

# Body collision: the seven Unity capsules approximated by spheres on Furina's own bones.
spheres = []
chest = ue_vec('Chest'); spine = ue_vec('Spine')
spheres.append(('Spine', scale(chest, .5), 11.5))
for side in ('Left', 'Right'):
    knee = ue_vec(side + ' knee'); ankle = ue_vec(side + ' ankle'); toe = ue_vec(side + ' toe')
    for f in (.2, .5, .8): spheres.append((side + ' leg', scale(knee, f), 8.2))
    spheres.append((side + ' knee', (0, 0, 0), 6.5))
    for f in (.35, .7): spheres.append((side + ' knee', scale(ankle, f), 5.5))
    spheres.append((side + ' ankle', scale(toe, .5), 4.5))
# Furina's root joint (Hips) carries the FBX x100 unit scale, so bone-local offsets are in metres.
sph_text = ','.join('(DrivingBone=(BoneName="%s"),SphereLocalOffset=%s,LimitRadius=%.2f,LimitType=Outer)' % (ue_name(b), v(scale(o, .01)), r) for b, o, r in spheres)

def body(bone):
    c = by[bone]
    L = c['limit']; twist = min(12.0, L * .35)
    r = c['radius'] * 100
    return ('(BoundBone=(BoneName="%s"),BoxExtents=(X=%.2f,Y=%.2f,Z=%.2f),LocalJointOffset=(X=0,Y=0,Z=0),'
            'ConstraintSetup=(LinearXLimitType=Limited,LinearYLimitType=Limited,LinearZLimitType=Limited,'
            'LinearAxesMin=(X=0,Y=0,Z=0),LinearAxesMax=(X=0,Y=0,Z=0),AngularConstraintType=Angular,TwistAxis=AxisY,AngularTargetAxis=AxisY,ConeAngle=0,'
            'AngularLimitsMin=(X=%.2f,Y=%.2f,Z=%.2f),AngularLimitsMax=(X=%.2f,Y=%.2f,Z=%.2f),AngularTarget=(X=0,Y=0,Z=0)),'
            'CollisionType=CustomSphere,SphereCollisionRadius=%.3f)') % (
        bone, r * 1.6, r * 2.5, r * 1.6, -L, -twist, -L, L, twist, L, r)

POSE = "PinType.PinCategory=\"struct\",PinType.PinSubCategory=\"\",PinType.PinSubCategoryObject=\"/Script/CoreUObject.ScriptStruct'/Script/Engine.%s'\",PinType.PinSubCategoryMemberReference=(),PinType.PinValueType=(),PinType.ContainerType=None,PinType.bIsReference=False,PinType.bIsConst=False,PinType.bIsWeakPointer=False,PinType.bIsUObjectWrapper=False,PinType.bSerializeAsSinglePrecisionFloat=False"

def pin(pid, name, struct, out, link=None):
    s = 'CustomProperties Pin (PinId=%s,PinName="%s",' % (pid, name)
    if out: s += 'Direction="EGPD_Output",'
    s += POSE % struct + ','
    if not out: s += 'DefaultValue="(LinkID=-1,SourceLinkID=-1)",AutogeneratedDefaultValue="(LinkID=-1,SourceLinkID=-1)",'
    if link: s += 'LinkedTo=(%s %s,),' % link
    s += 'PersistentGuid=00000000000000000000000000000000,bHidden=False,bNotConnectable=False,bDefaultValueIsReadOnly=False,bDefaultValueIsIgnored=False,bAdvancedView=False,bOrphanedPin=False,)'
    return s

nodes = []  # (cls, name, nodetext, x, y, pins)
X = -2400
retarget_out = gid()
l2c_in, l2c_out = gid(), gid()
ad = [(gid(), gid()) for _ in chains]
c2l_in, c2l_out = gid(), gid()

nodes.append(('/Script/IKRigDeveloper.AnimGraphNode_RetargetPoseFromMesh', 'AnimGraphNode_RetargetPoseFromMesh_0',
              "(RetargetFrom=ParentSkeletalMeshComponent,IKRetargeterAsset=\"/Script/IKRig.IKRetargeter'/Game/Furina/Retarget/RTG_Manny_To_Furina.RTG_Manny_To_Furina'\")",
              X, 0, [pin(retarget_out, 'Pose', 'PoseLink', True, ('AnimGraphNode_LocalToComponentSpace_0', l2c_in))]))
first_target = ('AnimGraphNode_AnimDynamics_0', ad[0][0])
nodes.append(('/Script/AnimGraph.AnimGraphNode_LocalToComponentSpace', 'AnimGraphNode_LocalToComponentSpace_0', None, X + 400, 0,
              [pin(l2c_in, 'LocalPose', 'PoseLink', False, ('AnimGraphNode_RetargetPoseFromMesh_0', retarget_out)),
               pin(l2c_out, 'ComponentPose', 'ComponentSpacePoseLink', True, first_target)]))
for i, ch in enumerate(chains):
    long_layer = not ch[0].startswith('HB1')
    params = [by[b] for b in ch]
    stiff = sum(p['stiffness'] for p in params) / len(params)
    grav = sum(p['gravity'] for p in params) / len(params)
    acc = sum(p.get('parentInfluence', .3) for p in params) / len(params)
    nodetext = ('(BoundBone=(BoneName="%s"),ChainEnd=(BoneName="%s"),bChain=True,PhysicsBodyDefinitions=(%s),'
                'SimulationSpace=Component,GravityScale=%.3f,bLinearSpring=True,LinearSpringConstant=%.1f,'
                'ComponentLinearAccScale=(X=%.2f,Y=%.2f,Z=%.2f),ComponentLinearVelScale=(X=%.2f,Y=%.2f,Z=0.05),ComponentAppliedLinearAccClamp=(X=3000,Y=3000,Z=3000),'
                'bOverrideLinearDamping=True,LinearDampingOverride=0.85,bOverrideAngularDamping=True,AngularDampingOverride=0.85,'
                'NumSolverIterationsPreUpdate=8,NumSolverIterationsPostUpdate=2,'
                'bUseSphericalLimits=True,SphericalLimits=(%s),bUsePlanarLimit=False)') % (
        ch[0], ch[-1], ','.join(body(b) for b in ch), grav, 45.0 * stiff * stiff,
        .55 if long_layer else .4, .55 if long_layer else .4, .3, .18 if long_layer else .1, .18 if long_layer else .1, sph_text)
    prev = ('AnimGraphNode_LocalToComponentSpace_0', l2c_out) if i == 0 else ('AnimGraphNode_AnimDynamics_%d' % (i - 1), ad[i - 1][1])
    nxt = ('AnimGraphNode_AnimDynamics_%d' % (i + 1), ad[i + 1][0]) if i + 1 < len(chains) else ('AnimGraphNode_ComponentToLocalSpace_0', c2l_in)
    nodes.append(('/Script/AnimGraph.AnimGraphNode_AnimDynamics', 'AnimGraphNode_AnimDynamics_%d' % i, nodetext,
                  X + 800 + (i % 6) * 320, 0 if i < 6 else 360,
                  [pin(ad[i][0], 'ComponentPose', 'ComponentSpacePoseLink', False, prev),
                   pin(ad[i][1], 'Pose', 'ComponentSpacePoseLink', True, nxt)]))
nodes.append(('/Script/AnimGraph.AnimGraphNode_ComponentToLocalSpace', 'AnimGraphNode_ComponentToLocalSpace_0', None, X + 800 + 6 * 320, 360,
              [pin(c2l_in, 'ComponentPose', 'ComponentSpacePoseLink', False, ('AnimGraphNode_AnimDynamics_%d' % (len(chains) - 1), ad[-1][1])),
               pin(c2l_out, 'Pose', 'PoseLink', True)]))

out = []
for cls, name, nodetext, x, y, pins in nodes:
    out.append('Begin Object Class=%s Name="%s"' % (cls, name))
    if nodetext: out.append('   Node=%s' % nodetext)
    out.append('   NodePosX=%d' % x)
    out.append('   NodePosY=%d' % y)
    out.append('   NodeGuid=%s' % gid())
    for p in pins: out.append('   ' + p)
    out.append('End Object')
open(S + r'\abp_graph.t3d', 'w', encoding='utf-8', newline='\r\n').write('\n'.join(out) + '\n')
print('chains', len(chains), 'spheres', len(spheres), 'chars', sum(len(l) for l in out))
